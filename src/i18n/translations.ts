const messages: Record<LanguageCode, Record<TranslationKey, string>> = {
  ko: koMessages,
  en: enMessages,
};

function interpolate(message: string, params?: TranslationParams): string {
  if (!params) return message;
  return Object.entries(params).reduce(
    (nextMessage, [name, value]) =>
      nextMessage.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    message,
  );
}

export function translate(
  language: LanguageCode,
  key: TranslationKey,
  params?: TranslationParams,
): string {
  return interpolate(messages[language][key] ?? koMessages[key] ?? key, params);
}

export function translateLiteral(
  language: LanguageCode,
  text: string,
  params?: TranslationParams,
): string {
  if (language === 'ko') return interpolate(text, params);
  const exact = enLiteralMessages[text];
  if (exact) return interpolate(exact, params);

  const translatedWithPrefix = translateLiteralWithPrefix(text);
  if (translatedWithPrefix) return interpolate(translatedWithPrefix, params);

  return interpolate(text, params);
}

function translateLiteralWithPrefix(text: string): string | null {
  const prefixPairs: Array<[string, string]> = [
    ['모임 대상 · ', 'Target Members · '],
    ['활동 지역 · ', 'Region · '],
  ];

  for (const [koPrefix, enPrefix] of prefixPairs) {
    if (!text.startsWith(koPrefix)) continue;
    const tail = text.slice(koPrefix.length).trim();
    return `${enPrefix}${translateLiteralListTail(tail)}`;
  }

  const teamLabelMatch = text.match(/^([A-Z]|\d+)조$/);
  if (teamLabelMatch) {
    return `Group ${teamLabelMatch[1]}`;
  }

  const generationMatch = text.match(/^(\d+)기$/);
  if (generationMatch) {
    return `Generation ${generationMatch[1]}`;
  }

  return null;
}

function translateLiteralListTail(text: string): string {
  return text
    .split(',')
    .map((item) => item.trim())
    .map((item) => enLiteralMessages[item] ?? item)
    .join(', ');
}
